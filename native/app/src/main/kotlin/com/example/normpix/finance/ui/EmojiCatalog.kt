fun searchEmoji(query: String): List<EmojiChoice> {
    val wanted = query.trim().lowercase()
    val all = emojiCatalog.flatMap { it.emojis }.distinctBy { it.glyph }
    return if (wanted.isEmpty()) all else all.filter { wanted in it.label }
}
